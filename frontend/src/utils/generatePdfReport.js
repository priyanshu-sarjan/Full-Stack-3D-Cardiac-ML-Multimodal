import jsPDF from 'jspdf';

export async function generatePdfReport({
  canvasRef,
  predictions,
  features,
  patientPreset,
  copilotData,
  metrics
}) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;
  let y = 16;

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 28, 'F');

  // Title
  doc.setTextColor(244, 63, 94); // rose-500
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('CardioTwin 3D', margin, y);

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(11);
  doc.text('• Cardiovascular Hemodynamic & AI Diagnostic Support Report', margin + 46, y - 0.5);

  doc.setTextColor(148, 163, 184); // slate-400
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.text('Track A: Multimodal Cardiovascular Risk Prediction & Interactive 3D Visualization', margin, y + 6);
  y = 34;

  // Clinical Safety Disclaimer Alert Box (MANDATORY REQUIREMENT)
  doc.setFillColor(254, 243, 199); // amber-100
  doc.setDrawColor(245, 158, 11); // amber-500
  doc.setLineWidth(0.5);
  doc.roundedRect(margin, y, pageWidth - margin * 2, 13, 2, 2, 'FD');

  doc.setTextColor(180, 83, 9); // amber-700
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.text('MANDATORY CLINICAL SAFETY DISCLAIMER:', margin + 3, y + 4.5);
  doc.setFont('helvetica', 'normal');
  doc.text(
    'This report is generated by a multi-task machine learning research prototype for decision support and educational simulation only. Calibrated statistical risk estimates are not a substitute for formal diagnostic coronary angiography or direct clinical judgment.',
    margin + 3,
    y + 9,
    { maxWidth: pageWidth - margin * 2 - 6 }
  );
  y += 18;

  // Patient Demographic & Clinical Profile Table
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('1. Patient Clinical Profile & Physiological Baseline', margin, y);
  y += 5;

  doc.setFillColor(248, 250, 252);
  doc.rect(margin, y, pageWidth - margin * 2, 20, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.rect(margin, y, pageWidth - margin * 2, 20, 'S');

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(71, 85, 105);

  const col1 = margin + 3;
  const col2 = margin + 50;
  const col3 = margin + 98;
  const col4 = margin + 142;

  doc.text(`Patient ID: ${patientPreset?.name || 'Custom Case'}`, col1, y + 5);
  doc.text(`Age: ${features?.Age || 60} yrs | Sex: ${features?.Sex === 1 ? 'Male' : 'Female'}`, col1, y + 10);
  doc.text(`BMI: ${Number(features?.BMI || 27).toFixed(1)} kg/m²`, col1, y + 15);

  doc.text(`Blood Pressure: ${features?.BP || 130} mmHg`, col2, y + 5);
  doc.text(`Resting Heart Rate: ${features?.PR || 75} bpm`, col2, y + 10);
  doc.text(`Smoker: ${features?.['Current Smoker'] ? 'Yes' : 'No'}`, col2, y + 15);

  doc.text(`LDL: ${features?.LDL || 120} mg/dL`, col3, y + 5);
  doc.text(`HDL: ${features?.HDL || 40} mg/dL`, col3, y + 10);
  doc.text(`Triglycerides: ${features?.TG || 150} mg/dL`, col3, y + 15);

  doc.text(`Ejection Fraction (EF): ${features?.['EF-TTE'] || 50}%`, col4, y + 5);
  doc.text(`Echo RWMA: Region ${features?.['Region RWMA'] || 0}`, col4, y + 10);
  doc.text(`Fasting Sugar: ${features?.FBS || 100} mg/dL`, col4, y + 15);
  y += 25;

  // 3D Canvas Snapshot & Stenosis Risk Table Section
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('2. 3D Anatomical Hemodynamic Simulation & Vessel Stenosis Estimation', margin, y);
  y += 5;

  // Try to capture WebGL canvas snapshot
  let hasImage = false;
  if (canvasRef?.current) {
    try {
      const dataUrl = canvasRef.current.toDataURL('image/png');
      doc.addImage(dataUrl, 'PNG', margin, y, 76, 54);
      doc.setDrawColor(203, 213, 225);
      doc.rect(margin, y, 76, 54);
      hasImage = true;
    } catch (err) {
      console.warn('Canvas export skipped:', err);
    }
  }

  // Vessel Risk Table on right side of 3D image
  const tableX = hasImage ? margin + 80 : margin;
  const tableW = hasImage ? pageWidth - margin - tableX : pageWidth - margin * 2;

  doc.setFillColor(241, 245, 249);
  doc.rect(tableX, y, tableW, 7, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(30, 41, 59);
  doc.text('Target Vessel', tableX + 3, y + 4.5);
  doc.text('Probability (CI)', tableX + 38, y + 4.5);
  doc.text('Clinical Risk Tier', tableX + 70, y + 4.5);

  const vesselRows = [
    { name: 'Overall CAD Status', data: predictions?.CAD },
    { name: 'LAD (Left Anterior Descending)', data: predictions?.LAD },
    { name: 'LCX (Left Circumflex)', data: predictions?.LCX },
    { name: 'RCA (Right Coronary Artery)', data: predictions?.RCA }
  ];

  let rowY = y + 7;
  vesselRows.forEach((row, idx) => {
    doc.setFillColor(idx % 2 === 0 ? 255 : 248, idx % 2 === 0 ? 255 : 250, idx % 2 === 0 ? 255 : 252);
    doc.rect(tableX, rowY, tableW, 11, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.line(tableX, rowY + 11, tableX + tableW, rowY + 11);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(15, 23, 42);
    doc.text(row.name, tableX + 3, rowY + 5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(row.data?.ci_formatted || 'N/A', tableX + 38, rowY + 5);

    const isHigh = (row.data?.percentage || 0) >= 70;
    const isUncertain = row.data?.is_uncertain;
    doc.setFont('helvetica', 'bold');
    if (isUncertain) {
      doc.setTextColor(217, 119, 6);
      doc.text('Borderline Uncertainty', tableX + 70, rowY + 5);
    } else if (isHigh) {
      doc.setTextColor(225, 29, 72);
      doc.text('≥70% High Stenosis', tableX + 70, rowY + 5);
    } else if ((row.data?.percentage || 0) >= 50) {
      doc.setTextColor(234, 88, 12);
      doc.text('≥50% Elevated', tableX + 70, rowY + 5);
    } else {
      doc.setTextColor(16, 185, 129);
      doc.text('Low Risk / Normal', tableX + 70, rowY + 5);
    }

    rowY += 11;
  });

  y += 58;

  // 3. Isolated Feature Attribution (SHAP)
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('3. Key Attributions & Biomarker Drivers (SHAP Decomposition)', margin, y);
  y += 5;

  const topDrivers = copilotData?.top_drivers || [
    'Regional Wall Motion Abnormality (RWMA) in correlated myocardial territory.',
    'Resting blood pressure and metabolic cholesterol biomarkers.',
    'Electrocardiographic ST-segment and T-wave alterations.'
  ];

  doc.setFillColor(248, 250, 252);
  doc.rect(margin, y, pageWidth - margin * 2, 22, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.rect(margin, y, pageWidth - margin * 2, 22, 'S');

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(51, 65, 85);
  topDrivers.slice(0, 3).forEach((driver, idx) => {
    doc.text(`• ${driver}`, margin + 3, y + 6 + idx * 5.5, { maxWidth: pageWidth - margin * 2 - 6 });
  });
  y += 28;

  // 4. Clinical Diagnostic Copilot Impression & Action Plan
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('4. Diagnostic Impression & Recommended Clinical Action Plan', margin, y);
  y += 5;

  doc.setFillColor(241, 245, 249);
  doc.rect(margin, y, pageWidth - margin * 2, 24, 'F');
  doc.setDrawColor(203, 213, 225);
  doc.rect(margin, y, pageWidth - margin * 2, 24, 'S');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(225, 29, 72);
  doc.text(`Stratification: ${copilotData?.urgency || 'Clinical Evaluation'}`, margin + 3, y + 5);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(51, 65, 85);
  doc.text(`Primary Culprit: ${copilotData?.culprit_vessel || 'LAD'} (${copilotData?.culprit_score || 85}%)`, margin + 3, y + 10);
  doc.text(`Action Plan: ${copilotData?.imaging_recommendation || 'Prompt CCTA and Guideline-Directed Medical Therapy'}`, margin + 3, y + 15, { maxWidth: pageWidth - margin * 2 - 6 });

  // Footer
  doc.setFontSize(7.5);
  doc.setTextColor(148, 163, 184);
  doc.text(`Report Generated: ${new Date().toISOString()} • CardioTwin 3D AI Platform`, margin, pageHeight - 8);
  doc.text('Page 1 of 1', pageWidth - margin - 16, pageHeight - 8);

  // Save PDF
  const filename = `CardioTwin3D_Report_${patientPreset?.id || 'Case'}.pdf`;
  doc.save(filename);
}
